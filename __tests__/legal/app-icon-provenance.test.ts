import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';

describe('redistributable app icon source and derivatives', () => {
  it('uses original, font-independent vector geometry without embedded or remote artwork', () => {
    const svg = readFileSync('public/app-icon.svg', 'utf8');
    expect(svg).toContain('SPDX-License-Identifier: Apache-2.0');
    expect(svg).not.toMatch(/<(?:text|image|script|foreignObject)\b|\b(?:href|font-family)=/i);
    expect(svg).toContain('viewBox="0 0 1024 1024"');
  });

  it('shares the IA strokes between the app icon and README wordmark', () => {
    const icon = readFileSync('public/app-icon.svg', 'utf8');
    const wordmark = readFileSync('docs/media/investatlas-logo.svg', 'utf8');
    const paths = (svg: string) => Array.from(svg.matchAll(/<path d="([^"]+)"/g), match => match[1]);
    expect(icon).not.toContain('<rect');
    expect(wordmark.match(/<rect\b/g)).toHaveLength(1);
    expect(paths(icon)).toHaveLength(2);
    expect(paths(wordmark)).toEqual(paths(icon));
  });

  it('binds every shipped icon to its documented source and exact generated bytes', () => {
    const provenance = JSON.parse(readFileSync('ASSET_PROVENANCE.json', 'utf8'));
    expect(provenance.license).toBe('Apache-2.0');
    expect(provenance.source).toBe('public/app-icon.svg');
    expect(provenance.assets.map((asset: { path: string }) => asset.path).sort()).toEqual([
      'public/app-icon-192.png', 'public/app-icon-512.png', 'public/app-icon.svg',
      'public/apple-touch-icon.png', 'src/app/favicon.ico',
    ].sort());
    for (const asset of provenance.assets) {
      const bytes = readFileSync(asset.path);
      expect(createHash('sha256').update(bytes).digest('hex')).toBe(asset.sha256);
      expect(asset.license).toBe('Apache-2.0');
    }
    for (const [name, size] of [['app-icon-192.png', 192], ['app-icon-512.png', 512], ['apple-touch-icon.png', 180]] as const) {
      const png = readFileSync(`public/${name}`);
      expect(png.subarray(0, 8)).toEqual(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
      expect([png.readUInt32BE(16), png.readUInt32BE(20)]).toEqual([size, size]);
    }
    const ico = readFileSync('src/app/favicon.ico');
    expect(ico.readUInt16LE(0)).toBe(0);
    expect(ico.readUInt16LE(2)).toBe(1);
    expect(ico.readUInt16LE(4)).toBe(3);
    for (let i = 0; i < 3; i++) {
      const entry = 6 + i * 16;
      expect(ico[entry]).toBe([16, 32, 48][i]);
      expect(ico[entry + 1]).toBe(ico[entry]);
      const length = ico.readUInt32LE(entry + 8);
      const offset = ico.readUInt32LE(entry + 12);
      expect(offset + length).toBeLessThanOrEqual(ico.length);
      expect(ico.subarray(offset, offset + 8)).toEqual(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
    }
  });
});
