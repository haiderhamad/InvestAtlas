/**
 * Metal purity / fineness utilities.
 *
 * Gold and silver are traded at a spot price that represents the purest
 * form (999.9 fine).  Physical bullion comes in different fineness levels.
 * This module provides the purity multipliers and helpers to convert a
 * spot price per troy ounce into a price per gram at a given fineness.
 */

export interface MetalPurityOption {
  /** Fineness expressed in parts-per-thousand, e.g. 999, 750 */
  fineness: number;
  /** Human-readable label */
  label: string;
  /** Short karat or quality label shown as a badge */
  badge: string;
}

/** 1 troy ounce in grams */
export const TROY_OUNCE_GRAMS = 31.1035;

export const GOLD_PURITY_OPTIONS: MetalPurityOption[] = [
  { fineness: 999.9, label: '999.9 — Investment Grade', badge: '24K+' },
  { fineness: 999,   label: '999 — 24 Karat',           badge: '24K' },
  { fineness: 916,   label: '916 — 22 Karat',           badge: '22K' },
  { fineness: 900,   label: '900 — 21.6 Karat',         badge: '21.6K' },
  { fineness: 750,   label: '750 — 18 Karat',           badge: '18K' },
  { fineness: 585,   label: '585 — 14 Karat',           badge: '14K' },
  { fineness: 333,   label: '333 — 8 Karat',            badge: '8K' },
];

export const SILVER_PURITY_OPTIONS: MetalPurityOption[] = [
  { fineness: 999.9, label: '999.9 — Investment Grade', badge: 'Fine' },
  { fineness: 999,   label: '999 — Fine Silver',        badge: '999' },
  { fineness: 925,   label: '925 — Sterling Silver',    badge: '925' },
  { fineness: 900,   label: '900 — Coin Silver',        badge: '900' },
  { fineness: 800,   label: '800',                       badge: '800' },
];

/**
 * Returns the decimal purity ratio (0 – 1) for a given fineness.
 * e.g. 999 → 0.999, 750 → 0.750
 */
export function getMetalPurityRatio(fineness: number): number {
  return fineness / 1000;
}

/**
 * Converts a spot price (USD or EUR per troy ounce for pure metal)
 * into price per gram at the given fineness.
 */
export function spotPricePerGram(
  spotPerOz: number,
  fineness: number,
): number {
  const ratio = getMetalPurityRatio(fineness);
  return (spotPerOz * ratio) / TROY_OUNCE_GRAMS;
}

/**
 * Returns the appropriate purity options for a metal symbol.
 */
export function getPurityOptionsForMetal(symbol: string): MetalPurityOption[] {
  const normalized = symbol.trim().toUpperCase();
  if (normalized === 'SILVER') return SILVER_PURITY_OPTIONS;
  // Default to gold purity options for GOLD and any future metals
  return GOLD_PURITY_OPTIONS;
}

function getLegacyFinenessSegment(
  option: MetalPurityOption,
): string {
  return `Fineness: ${option.label}`;
}

/**
 * Reads only the exact note fragment generated by the former InvestAtlas
 * metal form. Arbitrary free text is intentionally not interpreted as ledger
 * data. Conflicting legacy fragments remain unknown.
 */
export function parseLegacyMetalFineness(
  notes: string | undefined,
  symbol: string,
): number | undefined {
  if (!notes) return undefined;

  const options = getPurityOptionsForMetal(symbol);
  const candidateSegments = notes
    .split('|')
    .map((segment) => segment.trim())
    .filter((segment) => segment.startsWith('Fineness:'));
  const matches = candidateSegments.map((segment) =>
    options.find((candidate) => {
      const generated = getLegacyFinenessSegment(candidate);
      return segment === generated
        || segment === `${generated} (Incoming Transfer)`;
    })?.fineness);

  if (
    matches.length === 0
    || matches.some((value) => value === undefined || value !== matches[0])
  ) {
    return undefined;
  }

  return matches[0] as number;
}

/**
 * Removes only the exact legacy form fragment after it has been promoted to
 * the structured `metalFineness` field. User-authored notes are preserved.
 */
export function stripLegacyMetalFinenessNote(
  notes: string | undefined,
  symbol: string,
): string {
  if (!notes) return '';
  if (parseLegacyMetalFineness(notes, symbol) === undefined) {
    return notes;
  }

  const generatedSegments = new Set(
    getPurityOptionsForMetal(symbol).flatMap((option) => {
      const generated = getLegacyFinenessSegment(option);
      return [generated, `${generated} (Incoming Transfer)`];
    }),
  );

  return notes
    .split('|')
    .map((segment) => segment.trim())
    .filter((segment) => segment.length > 0 && !generatedSegments.has(segment))
    .join(' | ');
}
