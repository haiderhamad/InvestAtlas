/**
 * TradingView Pine Script Export Module
 * 
 * Generates TradingView-compatible Pine Script code from optimized strategies.
 * Supports both Indicator mode (visual signals) and Strategy mode (backtesting).
 * 
 * Maps internal strategy rules to Pine Script logic with full parameter export.
 * 
 * KNOWN DIFFERENCES vs. Internal Backtesting:
 * - TradingView uses its own price feed (may differ from CoinGecko/Yahoo historical data)
 * - Slippage model may differ (TV uses fixed points, internal uses percentage)
 * - Fee calculation: TV uses per-trade commission, internal supports percentage and flat order fees
 * - Candle timestamps may differ based on exchange selected in TV
 * - Internal backtest closes open positions at end of period; TV may not
 * These differences are documented in the exported script comments.
 */

import type { BacktestParameters } from '@/lib/strategy/models';
import { resolveBacktestFeeMode } from './fee-model';
import type { BacktestResult } from './types';

export type PineExportMode = 'indicator' | 'strategy';

export interface PineExportOptions {
  mode: PineExportMode;
  includeAlerts: boolean;
  includeComments: boolean;
  confirmOnClose: boolean; // Wait for candle close before signal
  coinName: string;
  backtestResult?: BacktestResult;
}

/**
 * Generate TradingView Pine Script from a backtest result
 */
export function generatePineScript(
  params: BacktestParameters,
  options: PineExportOptions
): string {
  const {
    mode,
    includeAlerts,
    includeComments,
    confirmOnClose,
    coinName,
    backtestResult,
  } = options;

  const lines: string[] = [];
  const strategyName = getStrategyName(params, coinName);
  
  // Header
  lines.push(`// =============================================================================`);
  lines.push(`// ${strategyName}`);
  lines.push(`// Generated by InvestAtlas Strategy Lab`);
  lines.push(`// Export Date: ${new Date().toISOString()}`);
  if (backtestResult) {
    lines.push(`// Backtest Period: ${backtestResult.startDate} to ${backtestResult.endDate}`);
    lines.push(`// Total Return: ${backtestResult.metrics.totalReturnPct.toFixed(2)}%`);
    lines.push(`// Win Rate: ${backtestResult.metrics.winRate.toFixed(1)}%`);
    lines.push(`// Max Drawdown: ${backtestResult.metrics.maxDrawdownPct.toFixed(2)}%`);
    lines.push(`// Sharpe Ratio: ${backtestResult.metrics.sharpeRatio.toFixed(3)}`);
    lines.push(`// Total Trades: ${backtestResult.metrics.totalTrades}`);
  }
  lines.push(`// =============================================================================`);
  
  if (includeComments) {
    lines.push(`// IMPORTANT: This script was generated from historical backtesting.`);
    lines.push(`// Past performance does not guarantee future results.`);
    lines.push(`// Differences between InvestAtlas internal backtest and TradingView:`);
    lines.push(`//   - Price data source may differ (CoinGecko/Yahoo vs. chart feed)`);
    lines.push(`//   - Fee/slippage models differ slightly`);
    lines.push(`//   - Candle timestamps depend on TradingView chart exchange`);
    lines.push(`// Always validate signals before trading.`);
    lines.push(``);
  }
  
  // Pine Script version
  lines.push(`//@version=5`);
  
  // Indicator or Strategy declaration
  if (mode === 'strategy') {
    const feeMode = resolveBacktestFeeMode(params);
    const feeStr =
      feeMode === 'flat'
        ? (params.flatFeeAmount || 0).toFixed(2)
        : (params.feePercent || 0.25).toFixed(2);
    const slippageStr = Math.round((params.slippagePercent || 0.1) * 10);
    const commissionType =
      feeMode === 'flat'
        ? 'strategy.commission.cash_per_order'
        : 'strategy.commission.percent';
    lines.push(`strategy("${strategyName}", overlay=true, default_qty_type=strategy.percent_of_equity, default_qty_value=100, commission_type=${commissionType}, commission_value=${feeStr}, slippage=${slippageStr})`);
  } else {
    lines.push(`indicator("${strategyName}", overlay=true)`);
  }
  lines.push(``);
  
  // Generate based on strategy type
  switch (params.strategyType) {
    case 'single_sma':
      generateSingleSMA(lines, params, mode, includeAlerts, includeComments, confirmOnClose);
      break;
    case 'dual_sma':
      generateDualSMA(lines, params, mode, includeAlerts, includeComments, confirmOnClose);
      break;

  }
  
  return lines.join('\n');
}

/**
 * Generate Single-SMA strategy Pine Script
 */
function generateSingleSMA(
  lines: string[],
  params: BacktestParameters,
  mode: PineExportMode,
  includeAlerts: boolean,
  includeComments: boolean,
  confirmOnClose: boolean
): void {
  const period = params.smaPeriod || 50;
  
  if (includeComments) {
    lines.push(`// --- Single SMA Strategy ---`);
    lines.push(`// Buy when price crosses above SMA(${period})`);
    lines.push(`// Sell when price crosses below SMA(${period})`);
    lines.push(``);
  }
  
  // Input parameters
  lines.push(`// Input Parameters`);
  lines.push(`sma_period = input.int(${period}, title="SMA Period", minval=2, maxval=500)`);
  lines.push(``);
  
  // Calculate SMA
  lines.push(`// Calculate SMA`);
  lines.push(`sma_val = ta.sma(close, sma_period)`);
  lines.push(``);
  
  // Plot SMA
  lines.push(`// Plot SMA`);
  lines.push(`plot(sma_val, color=color.new(color.blue, 0), linewidth=2, title="SMA")`);
  lines.push(``);
  
  // Signal logic
  const crossSrc = confirmOnClose ? 'close' : 'close';
  lines.push(`// Signal Logic${confirmOnClose ? ' (confirmed on candle close)' : ''}`);
  lines.push(`buy_signal = ta.crossover(${crossSrc}, sma_val)`);
  lines.push(`sell_signal = ta.crossunder(${crossSrc}, sma_val)`);
  lines.push(``);
  

  
  // Entry/Exit logic
  generateEntryExit(lines, mode, includeAlerts, includeComments, params);
}

/**
 * Generate Dual-SMA strategy Pine Script
 */
function generateDualSMA(
  lines: string[],
  params: BacktestParameters,
  mode: PineExportMode,
  includeAlerts: boolean,
  includeComments: boolean,
  confirmOnClose: boolean
): void {
  const fast = params.fastPeriod || 20;
  const slow = params.slowPeriod || 50;
  
  if (includeComments) {
    lines.push(`// --- Dual SMA Crossover Strategy ---`);
    lines.push(`// Buy on Golden Cross: SMA(${fast}) crosses above SMA(${slow})`);
    lines.push(`// Sell on Death Cross: SMA(${fast}) crosses below SMA(${slow})`);
    lines.push(``);
  }
  
  // Input parameters
  lines.push(`// Input Parameters`);
  lines.push(`fast_period = input.int(${fast}, title="Fast SMA Period", minval=2, maxval=500)`);
  lines.push(`slow_period = input.int(${slow}, title="Slow SMA Period", minval=2, maxval=500)`);
  lines.push(``);
  
  // Calculate SMAs
  lines.push(`// Calculate SMAs`);
  lines.push(`fast_sma = ta.sma(close, fast_period)`);
  lines.push(`slow_sma = ta.sma(close, slow_period)`);
  lines.push(``);
  
  // Plot SMAs
  lines.push(`// Plot SMAs`);
  lines.push(`plot(fast_sma, color=color.new(color.green, 0), linewidth=2, title="Fast SMA")`);
  lines.push(`plot(slow_sma, color=color.new(color.red, 0), linewidth=2, title="Slow SMA")`);
  lines.push(``);
  
  // Signal logic
  lines.push(`// Signal Logic${confirmOnClose ? ' (confirmed on candle close)' : ''}`);
  lines.push(`buy_signal = ta.crossover(fast_sma, slow_sma)`);
  lines.push(`sell_signal = ta.crossunder(fast_sma, slow_sma)`);
  lines.push(``);
  

  
  // Entry/Exit logic
  generateEntryExit(lines, mode, includeAlerts, includeComments, params);
}





/**
 * Generate entry/exit logic (indicator or strategy mode)
 */
function generateEntryExit(
  lines: string[],
  mode: PineExportMode,
  includeAlerts: boolean,
  includeComments: boolean,
  params: BacktestParameters
): void {
  if (mode === 'strategy') {
    if (includeComments) {
      lines.push(`// Strategy Entry / Exit`);
    }
    lines.push(`if (buy_signal)`);
    lines.push(`    strategy.entry("buy", strategy.long)`);
    lines.push(``);
    lines.push(`if (sell_signal)`);
    lines.push(`    strategy.close("buy")`);


  } else {
    // Indicator mode — visual markers
    if (includeComments) {
      lines.push(`// Visual Buy/Sell Signals`);
    }
  }
  
  lines.push(``);
  
  // Signal markers (both modes)
  lines.push(`// Buy/Sell Markers`);
  lines.push(`plotshape(buy_signal, title="Buy Signal", location=location.belowbar, color=color.new(color.green, 0), style=shape.labelup, text="BUY", size=size.small)`);
  lines.push(`plotshape(sell_signal, title="Sell Signal", location=location.abovebar, color=color.new(color.red, 0), style=shape.labeldown, text="SELL", size=size.small)`);
  
  // Background coloring
  lines.push(``);
  lines.push(`// Background color for active position`);
  if (mode === 'strategy') {
    lines.push(`bgcolor(strategy.position_size > 0 ? color.new(color.green, 90) : na, title="In Position")`);
  } else {
    lines.push(`var bool in_position = false`);
    lines.push(`if (buy_signal)`);
    lines.push(`    in_position := true`);
    lines.push(`if (sell_signal)`);
    lines.push(`    in_position := false`);
    lines.push(`bgcolor(in_position ? color.new(color.green, 90) : na, title="In Position")`);
  }
  
  // Alerts
  if (includeAlerts) {
    lines.push(``);
    lines.push(`// Alert Conditions`);
    lines.push(`alertcondition(buy_signal, title="Buy Alert", message="BUY signal for ${params.strategyType} strategy")`);
    lines.push(`alertcondition(sell_signal, title="Sell Alert", message="SELL signal for ${params.strategyType} strategy")`);
  }
}

/**
 * Get a human-readable strategy name
 */
function getStrategyName(params: BacktestParameters, coinName: string): string {
  switch (params.strategyType) {
    case 'single_sma':
      return `InvestAtlas: ${coinName} SMA(${params.smaPeriod})`;
    case 'dual_sma':
      return `InvestAtlas: ${coinName} SMA(${params.fastPeriod}/${params.slowPeriod}) Crossover`;

    default:
      return `InvestAtlas: ${coinName} Strategy`;
  }
}

/**
 * Generate export metadata for documentation
 */
export function generateExportMetadata(
  params: BacktestParameters,
  result: BacktestResult,
  coinName: string
): Record<string, string | number> {
  return {
    strategyName: getStrategyName(params, coinName),
    coin: coinName,
    strategyType: params.strategyType,
    testPeriod: `${result.startDate} to ${result.endDate}`,
    totalReturn: `${result.metrics.totalReturnPct.toFixed(2)}%`,
    winRate: `${result.metrics.winRate.toFixed(1)}%`,
    maxDrawdown: `${result.metrics.maxDrawdownPct.toFixed(2)}%`,
    sharpeRatio: result.metrics.sharpeRatio.toFixed(3),
    totalTrades: result.metrics.totalTrades,
    profitFactor: result.metrics.profitFactor.toFixed(2),
    buyHoldComparison: `${result.metrics.buyHoldReturnPct.toFixed(2)}%`,
    exportTimestamp: new Date().toISOString(),
    exportVersion: '1.0',
  };
}
